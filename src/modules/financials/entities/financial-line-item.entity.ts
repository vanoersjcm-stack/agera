import { Column, CreateDateColumn, Entity, PrimaryGeneratedColumn, UpdateDateColumn } from 'typeorm';

export const FINANCIAL_CATEGORIES = ['revenue', 'cogs', 'opex', 'license_fee'] as const;
export type FinancialCategory = (typeof FINANCIAL_CATEGORIES)[number];

export function isFinancialCategory(value: unknown): value is FinancialCategory {
  return FINANCIAL_CATEGORIES.includes(value as FinancialCategory);
}

/** RLS-protected: access only through TenantTransaction. Amounts are decimal strings (NUMERIC(15,2)). */
@Entity({ name: 'financial_line_items' })
export class FinancialLineItem {
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  @Column({ name: 'tenant_id', type: 'uuid' })
  tenantId!: string;

  @Column({ name: 'model_id', type: 'uuid' })
  modelId!: string;

  @Column({ type: 'varchar', length: 50 })
  category!: FinancialCategory;

  @Column({ type: 'varchar', length: 100, nullable: true })
  subcategory!: string | null;

  @Column({ name: 'period_code', type: 'varchar', length: 10 })
  periodCode!: string;

  @Column({ name: 'projected_amount', type: 'numeric', precision: 15, scale: 2 })
  projectedAmount!: string;

  @Column({ name: 'actual_amount', type: 'numeric', precision: 15, scale: 2, nullable: true })
  actualAmount!: string | null;

  /** Generated by PostgreSQL: actual_amount - projected_amount. */
  @Column({ type: 'numeric', precision: 15, scale: 2, nullable: true, insert: false, update: false })
  variance!: string | null;

  @Column({ type: 'varchar', length: 3, default: 'EUR' })
  currency!: string;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz', precision: 3 })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz', precision: 3 })
  updatedAt!: Date;
}
